test('same-site lock serializes two independent callers before snapshots or live writes', { timeout: 10000 }, async t => {
  const fix = await fixture(t);
  const helperFile = await put(fix.root, 'lock-test-helper.sh', helper);
  const installerFile = await put(fix.root, 'lock-test-installer.sh', installer);
  await put(fix.site, 'data/seo/school-redirects.nginx.conf', '# SEDA_SCHOOL_REDIRECT generated by scripts/migrate-school-pages.mjs\nlocation = /old-school/ { return 301 "https://sgeda.org.cn/cms-published/live/"; }\n');
  const log = path.join(fix.root, 'lock-order.log');
  const prefix = `set -euo pipefail; cd ${quote(fix.site)}; source ${quote(helperFile)}; ${fix.begin}; `;
  const suffix = `deploy_site_transaction_install_redirects ${quote(installerFile)}; deploy_site_transaction_commit; `;
  function start(script) {
    const child = spawn('bash', ['-c', script], { env: fix.env, stdio: ['ignore', 'pipe', 'pipe'] });
    let stderr = '';
    child.stderr.on('data', bytes => { stderr += bytes; });
    child.stdout.resume();
    const finished = new Promise((resolve, reject) => {
      child.once('error', reject);
      child.once('close', code => resolve({ code, stderr }));
    });
    return { child, finished };
  }
  const first = start(prefix + `printf 'first-start\n' >> ${quote(log)}; sleep 0.3; ` + suffix + `printf 'first-end\n' >> ${quote(log)};`);
  let second;
  try {
    for (let attempt = 0; attempt < 100; attempt++) {
      try { await fs.access(log); break; } catch { await new Promise(resolve => setTimeout(resolve, 10)); }
    }
    assert.equal(await fs.readFile(log, 'utf8'), 'first-start\n');
    second = start(prefix + `printf 'second-enter\n' >> ${quote(log)}; ` + suffix);
    const [one, two] = await Promise.all([first.finished, second.finished]);
    assert.equal(one.code, 0, one.stderr);
    assert.equal(two.code, 0, two.stderr);
    assert.equal(await fs.readFile(log, 'utf8'), 'first-start\nfirst-end\nsecond-enter\n');
  } finally {
    if (first.child.exitCode === null) first.child.kill('SIGTERM');
    if (second?.child.exitCode === null) second.child.kill('SIGTERM');
    await Promise.all([first.finished, ...(second ? [second.finished] : [])]);
  }
});

