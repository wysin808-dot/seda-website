const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const helper = await fs.readFile(path.join(repository, 'scripts/deploy-site-transaction.sh'), 'utf8');
const installer = path.join(repository, 'scripts/install-school-redirects.sh');
const quote = s => `'${s.replaceAll("'", "'\\''")}'`;

async function put(root, name, content, mode) {
  const file = path.join(root, name);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, content);
  if (mode) await fs.chmod(file, mode);
  return file;
}

async function fixture(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'seda-deploy-transaction-'));
  await fs.chmod(root, 0o700);
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const site = path.join(root, 'site');
  await put(site, 'index.html', 'OLD FRONTEND\n');
  const content = `# Preserve every original byte: SSL/API/analytics and non-ASCII 中文\r\nserver { listen 80; server_name sgeda.org.cn; return 301 https://sgeda.org.cn$request_uri; }\r\nserver {\r\n    listen [::]:443 ssl http2;\r\n    server_name "sgeda.org.cn";\r\n    root "${site}";\r\n    ssl_certificate /fixture/existing.pem;\r\n    ssl_certificate_key /fixture/existing.key;\r\n    location /api/ { proxy_pass http://127.0.0.1:3002; proxy_set_header X-Test "brace { and # fragment"; }\r\n    location /analytics/ { proxy_pass http://127.0.0.1:3003; }\r\n}\r\n`;
  const config = await put(root, 'nginx/conf.d/arbitrary-live-name.conf', content);
  const include = await put(root, 'nginx/snippets/school-redirects.nginx.conf', '# old unused include\n');
  const source = await put(site, 'data/seo/school-redirects.nginx.conf', '# SEDA_SCHOOL_REDIRECT generated by scripts/migrate-school-pages.mjs\nlocation = /old-school/ { return 301 "https://sgeda.org.cn/new-target/#school-alpha"; }\n');
  const sources = await put(root, 'loaded.json', JSON.stringify([{ path: config }]));
  const log = path.join(root, 'commands.log');
  const active = path.join(root, 'active-rules');
  const nginx = await put(root, 'bin/nginx', `#!/usr/bin/env python3
import json, os
from pathlib import Path
import sys
with open(os.environ['FIX_LOG'], 'a') as out: out.write('nginx ' + sys.argv[1] + '\\n')
include = Path(os.environ['FIX_INCLUDE'])
new = include.exists() and b'new-target' in include.read_bytes()
if sys.argv[1] == '-t':
    if os.environ.get('FAIL_NEW_TEST') == '1' and new: sys.exit(31)
    if os.environ.get('FAIL_OLD_TEST') == '1' and not new: sys.exit(33)
if sys.argv[1] == '-T':
    if os.environ.get('FAIL_DISCOVERY') == '1':
        print('hidden fixture diagnostic secret', file=sys.stderr)
        sys.exit(34)
    referenced = False
    for entry in json.loads(Path(os.environ['FIX_SOURCES']).read_text()):
        data = entry['content'].encode() if 'content' in entry else Path(entry['path']).read_bytes()
        sys.stdout.buffer.write(('# configuration file ' + entry['path'] + ':\\n').encode() + data + b'\\n')
        referenced |= ('include ' + str(include) + ';').encode() in data
    if referenced and include.exists() and os.environ.get('OMIT_INCLUDE') != '1':
        sys.stdout.buffer.write(('# configuration file ' + str(include) + ':\\n').encode() + include.read_bytes() + b'\\n')
`, 0o755);
  const reload = await put(root, 'bin/reload', `#!/usr/bin/env python3
import os, sys
from pathlib import Path
with open(os.environ['FIX_LOG'], 'a') as out: out.write('reload ' + ' '.join(sys.argv[1:]) + '\\n')
include = Path(os.environ['FIX_INCLUDE'])
active = Path(os.environ['FIX_ACTIVE'])
config = Path(os.environ['FIX_CONFIG'])
if include.exists() and ('include ' + str(include) + ';').encode() in config.read_bytes(): active.write_bytes(include.read_bytes())
else: active.unlink(missing_ok=True)
if os.environ.get('FAIL_RELOAD') == '1' and include.exists() and b'new-target' in include.read_bytes(): sys.exit(32)
`, 0o755);
  const git = await put(root, 'bin/git', `#!/bin/sh
printf 'git %s\\n' "$*" >> "$FIX_LOG"
if [ "$3" = rev-parse ]; then echo old-sha; fi
`, 0o755);
  const bootstrap = await put(root, 'bootstrap-helper.sh', helper);
  const env = { ...process.env, FIX_SOURCES: sources, FIX_LOG: log, FIX_CONFIG: config, FIX_INCLUDE: include, FIX_ACTIVE: active };
  const txArgs = ['--test-mode', '--fixture-root', root, '--site-root', site, '--include-path', include,
    '--nginx-bin', nginx, '--reload-bin', reload, '--git-bin', git];
  const installArgs = ['--test-mode', '--fixture-root', root, '--site-root', site, '--include-path', include,
    '--source', source, '--nginx-bin', nginx, '--reload-bin', reload];
  const runInstaller = (extra = [], overrides = {}) => spawnSync('bash', [installer, ...installArgs, ...extra], {
    cwd: root, env: { ...env, ...overrides }, encoding: 'utf8', timeout: 10000,
  });
  const runTransaction = (extra = [], overrides = {}, postBegin = '') => spawnSync('bash', ['-c', `set -euo pipefail
source ${quote(bootstrap)}
rm -f -- ${quote(bootstrap)}
deploy_site_transaction_begin ${[...txArgs, ...extra].map(quote).join(' ')}
printf 'NEW FRONTEND\\n' > ${quote(path.join(site, 'index.html'))}
${postBegin}
deploy_site_transaction_install_redirects ${quote(installer)}
deploy_site_transaction_commit
`], { cwd: root, env: { ...env, ...overrides }, encoding: 'utf8', timeout: 10000 });
  const loaded = entries => fs.writeFile(sources, JSON.stringify(entries));
  return { root, site, content, config, include, source, sources, log, active, env, txArgs, installArgs,
    bootstrap, loaded, runInstaller, runTransaction };
}

function cleanLogs(result) {
  const logs = result.stdout + result.stderr;
  for (const forbidden of ['ssl_certificate', 'proxy_pass', 'Preserve every original byte', 'hidden fixture diagnostic secret']) {
    assert.ok(!logs.includes(forbidden), logs);
  }
}

async function unchanged(fix, result) {
  assert.notEqual(result.status, 0, result.stdout);
  assert.equal(await fs.readFile(fix.config, 'utf8'), fix.content);
  assert.equal(await fs.readFile(fix.include, 'utf8'), '# old unused include\n');
  cleanLogs(result);
}

test('self-contained first bootstrap discovers uniquely loaded conf.d file without either default site path', async t => {
  const fix = await fixture(t);
  await assert.rejects(fs.access(path.join(fix.root, 'nginx/sites-available/sgeda')), /ENOENT/);
  await assert.rejects(fs.access(path.join(fix.site, 'scripts')), /ENOENT/);
  const result = fix.runTransaction();
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout + result.stderr, /arbitrary-live-name\.conf/);
  await assert.rejects(fs.access(fix.bootstrap), /ENOENT/);
  const updated = await fs.readFile(fix.config, 'utf8');
  assert.equal(updated.replace(/    # BEGIN SEDA_SCHOOL_REDIRECT_INCLUDE\n    include [^\n]+;\n    # END SEDA_SCHOOL_REDIRECT_INCLUDE\n/, ''), fix.content);
  assert.equal(await fs.readFile(fix.active, 'utf8'), await fs.readFile(fix.source, 'utf8'));
  cleanLogs(result);
});

test('loaded sites-enabled relative symlink selects its regular conf.d target and never replaces the alias', async t => {
  const fix = await fixture(t);
  const enabled = path.join(fix.root, 'nginx/sites-enabled/live-canonical');
  await fs.mkdir(path.dirname(enabled));
  await fs.symlink('../conf.d/arbitrary-live-name.conf', enabled);
  await fix.loaded([{ path: enabled }]);
  const result = fix.runInstaller(['--config', fix.config, '--enabled-config', enabled]);
  assert.equal(result.status, 0, result.stderr);
  assert.equal(await fs.readlink(enabled), '../conf.d/arbitrary-live-name.conf');
  assert.equal((await fs.lstat(fix.config)).isFile(), true);
  cleanLogs(result);
});

for (const failure of ['FAIL_NEW_TEST', 'FAIL_RELOAD', 'OMIT_INCLUDE']) {
  test(`conf.d selected path is snapshotted and byte-restored on ${failure}, unrelated config is untouched`, async t => {
    const fix = await fixture(t);
    const unused = await put(fix.root, 'nginx/sites-available/sgeda', fix.content.replaceAll('sgeda.org.cn', 'unused.example'));
    const unusedBytes = await fs.readFile(unused);
    const result = fix.runTransaction([], { [failure]: '1' });
    await unchanged(fix, result);
    assert.match(result.stderr, /Frontend rollback complete/);
    assert.equal(await fs.readFile(path.join(fix.site, 'index.html'), 'utf8'), 'OLD FRONTEND\n');
    assert.deepEqual(await fs.readFile(unused), unusedBytes);
    await assert.rejects(fs.access(fix.active), /ENOENT/);
    const backup = (await fs.readdir(fix.root)).find(x => x.startsWith('sgeda-site-transaction-'));
    const manifest = JSON.parse(await fs.readFile(path.join(fix.root, backup, 'manifest.json')));
    assert.equal(manifest.nginx_paths.config, fix.config);
    assert.equal(manifest.nginx_paths.loaded, fix.config);
  });
}

