const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const installer = path.join(repository, 'scripts/install-school-redirects.sh');
const BEGIN = '# BEGIN SEDA_GIT_ACCESS_GUARD';
const END = '# END SEDA_GIT_ACCESS_GUARD';
const GUARD = `\n    ${BEGIN}\n    if ($uri ~ "^/+[.]git(?:/|$)") {\n        return 404;\n    }\n    ${END}\n`;
const SCHOOL = /    # BEGIN SEDA_SCHOOL_REDIRECT_INCLUDE\n    include [^\n]+;\n    # END SEDA_SCHOOL_REDIRECT_INCLUDE\n/;
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));

async function put(root, relative, bytes, mode) {
  const file = path.join(root, relative);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, bytes);
  if (mode) await fs.chmod(file, mode);
  return file;
}

// Self-contained fixture: no imports of other test modules and no real Git data.
async function fixture(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'seda-deploy-transaction-'));
  await fs.chmod(root, 0o700);
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const site = path.join(root, 'site');
  const cert = path.join(root, 'fixture.pem');
  const key = path.join(root, 'fixture.key');
  await put(site, 'index.html', '<h1>ordinary fixture HTML</h1>\n');
  const original = `# Preserve SSL/API/cache and all non-managed bytes 中文\nserver { listen 443 ssl; server_name www.sgeda.org.cn; ssl_certificate ${cert}; ssl_certificate_key ${key}; return 301 https://sgeda.org.cn$request_uri; }\n# CANONICAL\nserver {\n    listen 443 ssl;\n    server_name sgeda.org.cn;\n    root ${site};\n    ssl_certificate ${cert};\n    ssl_certificate_key ${key};\n    index index.html;\n    location = /.git/config { try_files $uri =404; add_header X-Exact fixture always; }\n    location /.git/objects/ { try_files $uri =404; add_header X-Long-Prefix fixture always; }\n    location ^~ /.git/objects/long/ { try_files $uri =404; add_header X-Long-Prefix fixture always; }\n    location ~ [.]?(?:css|js)$ { expires 7d; try_files $uri =404; add_header X-Cache fixture always; }\n    location = /api/config { return 200 "fixture API config"; }\n    location = /api/.git/config { return 200 "fixture nested API"; }\n    location / { try_files $uri $uri/ =404; }\n}\n`;
  const config = await put(root, 'nginx/conf.d/canonical.conf', original);
  const include = await put(root, 'nginx/snippets/school.conf', '# previous fixture include\n', 0o640);
  await fs.chmod(config, 0o640);
  const source = await put(root, 'generated-school.conf', '# SEDA_SCHOOL_REDIRECT generated by scripts/migrate-school-pages.mjs\nlocation = /old-school/ { return 301 "https://sgeda.org.cn/new-target/#school-alpha"; }\n');
  const log = path.join(root, 'commands.log');
  const nginx = await put(root, 'bin/fake-nginx', `#!/bin/sh
printf 'nginx %s\\n' "$1" >> "$FIX_LOG"
if [ "$1" = -t ] && [ "$FAIL_TEST" = 1 ]; then exit 31; fi
if [ "$1" = -T ]; then
  if [ "$FAIL_NEW_DUMP" = 1 ] && grep -Fq 'SEDA_GIT_ACCESS_GUARD' "$FIX_CONFIG"; then exit 32; fi
  if [ "$FAIL_REMOVE_DUMP" = 1 ] && [ ! -f "$FIX_INCLUDE" ]; then exit 33; fi
  printf '# configuration file %s:\\n' "$FIX_CONFIG"
  cat "$FIX_CONFIG"
  printf '\\n'
  if [ "$OMIT_INCLUDE" != 1 ] && [ -f "$FIX_INCLUDE" ] && grep -Fq "include $FIX_INCLUDE;" "$FIX_CONFIG"; then
    printf '# configuration file %s:\\n' "$FIX_INCLUDE"
    cat "$FIX_INCLUDE"
    printf '\\n'
  fi
fi
`, 0o755);
  const reload = await put(root, 'bin/fake-reload', '#!/bin/sh\nprintf "reload %s\\n" "$*" >> "$FIX_LOG"\nif [ "$FAIL_RELOAD" = 1 ]; then exit 34; fi\n', 0o755);
  const env = { ...process.env, FIX_LOG: log, FIX_CONFIG: config, FIX_INCLUDE: include };
  const args = [installer, '--test-mode', '--fixture-root', root, '--config', config,
    '--enabled-config', config, '--site-root', site, '--include-path', include,
    '--source', source, '--nginx-bin', nginx, '--reload-bin', reload];
  const run = (extra = [], overrides = {}) => spawnSync('bash', [...args, ...extra], {
    cwd: root, env: { ...env, ...overrides }, encoding: 'utf8', timeout: 10000,
  });
  return { root, site, cert, key, config, include, source, log, original, run };
}

function installedAtStart(text) {
  assert.equal(text.split(BEGIN).length - 1, 1);
  assert.equal(text.split(END).length - 1, 1);
  assert.ok(text.includes(`# CANONICAL\nserver {${GUARD}`));
  assert.ok(text.indexOf(BEGIN) < text.indexOf('    listen 443 ssl;'));
  assert.ok(!text.slice(0, text.indexOf('# CANONICAL')).includes(BEGIN));
}

test('offline dry runs are byte-idempotent and execute no Nginx/reload', async t => {
  const fix = await fixture(t);
  const before = await fs.readFile(fix.config);
  for (let i = 0; i < 2; i++) {
    const result = fix.run(['--dry-run']);
    assert.equal(result.status, 0, result.stderr);
    assert.match(result.stdout, /offline transform validated/);
    assert.deepEqual(await fs.readFile(fix.config), before);
    assert.equal(await fs.readFile(fix.include, 'utf8'), '# previous fixture include\n');
  }
  await assert.rejects(fs.access(fix.log), /ENOENT/);
  assert.equal(fix.run().status, 0);
  const installed = await fs.readFile(fix.config);
  assert.equal(fix.run(['--dry-run']).status, 0);
  assert.deepEqual(await fs.readFile(fix.config), installed);
});

test('installer selects canonical 443, preserves non-managed bytes/modes and second run never reloads', async t => {
  const fix = await fixture(t);
  assert.equal(fix.run().status, 0);
  const installed = await fs.readFile(fix.config, 'utf8');
  installedAtStart(installed);
  assert.equal(installed.replace(GUARD, '').replace(SCHOOL, ''), fix.original);
  assert.equal((await fs.stat(fix.config)).mode & 0o777, 0o640);
  assert.equal((await fs.stat(fix.include)).mode & 0o777, 0o640);
  assert.equal(fix.run().status, 0);
  assert.equal(await fs.readFile(fix.config, 'utf8'), installed);
  assert.equal((await fs.readFile(fix.log, 'utf8')).split('reload reload nginx').length - 1, 1);
  assert.deepEqual(await fs.readdir(path.dirname(fix.config)), ['canonical.conf']);
  assert.deepEqual(await fs.readdir(path.dirname(fix.include)), ['school.conf']);
});

test('legal direct-server guard is moved to server start, not duplicated; CRLF/invalid UTF-8 comments survive', async t => {
  const fix = await fixture(t);
  const bytes = Buffer.concat([Buffer.from(fix.original.replaceAll('\n', '\r\n')), Buffer.from([35, 32, 0xff, 10])]);
  await fs.writeFile(fix.config, bytes);
  assert.equal(fix.run().status, 0);
  const current = await fs.readFile(fix.config);
  const without = current.toString('latin1').replace(GUARD, '').replace(SCHOOL, '');
  assert.deepEqual(Buffer.from(without, 'latin1'), bytes);
  const moved = current.toString('latin1').replace(GUARD, '').replace('    location / {', `${GUARD}    location / {`);
  await fs.writeFile(fix.config, Buffer.from(moved, 'latin1'));
  const result = fix.run();
  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(await fs.readFile(fix.config), current);
});

test('--remove removes only school include and installs/retains guard even on an initially unguarded server', async t => {
  const fix = await fixture(t);
  assert.equal(fix.run(['--remove']).status, 0);
  const onlyGuard = await fs.readFile(fix.config, 'utf8');
  installedAtStart(onlyGuard);
  assert.equal(onlyGuard.replace(GUARD, ''), fix.original);
  await assert.rejects(fs.access(fix.include), /ENOENT/);
  assert.equal(fix.run(['--remove']).status, 0);
  assert.equal(await fs.readFile(fix.config, 'utf8'), onlyGuard);
  assert.equal(fix.run().status, 0);
  assert.equal(fix.run(['--remove']).status, 0);
  assert.equal(await fs.readFile(fix.config, 'utf8'), onlyGuard);
});

test('inline canonical server gets a first-scope guard without losing any original byte', async t => {
  const fix = await fixture(t);
  const canonical = `server { listen 443 ssl; server_name sgeda.org.cn; root ${fix.site}; location / { return 200 "ordinary fixture"; } }\n`;
  await fs.writeFile(fix.config, canonical);
  const result = fix.run(['--remove']);
  assert.equal(result.status, 0, result.stderr);
  const guarded = await fs.readFile(fix.config, 'utf8');
  assert.ok(guarded.startsWith(`server {${GUARD}`));
  assert.equal(guarded.replace(GUARD, ''), canonical);
  assert.equal(fix.run(['--remove']).status, 0);
  assert.equal(await fs.readFile(fix.config, 'utf8'), guarded);
});

test('quoted and commented braces do not disguise a legal direct-server guard as nested', async t => {
  const fix = await fixture(t);
  const original = fix.original.replace('    location / {', '    # unrelated { quoted } braces\n    location /quoted/ { add_header X-Test "brace { and } and # fragment"; }\n    location / {');
  await fs.writeFile(fix.config, original.replace('    location / {', `${GUARD}    location / {`));
  const result = fix.run();
  assert.equal(result.status, 0, result.stderr);
  const guarded = await fs.readFile(fix.config, 'utf8');
  installedAtStart(guarded);
  assert.equal(guarded.replace(GUARD, '').replace(SCHOOL, ''), original);
});

const invalidGuards = [
  ['missing end', s => s.replace('    listen 443 ssl;', `${GUARD.replace(END, '# absent end')}    listen 443 ssl;`)],
  ['missing begin', s => s.replace('    listen 443 ssl;', `${GUARD.replace(BEGIN, '# absent begin')}    listen 443 ssl;`)],
  ['reversed markers', s => s.replace('    listen 443 ssl;', `${GUARD.replace(BEGIN, '# placeholder').replace(END, BEGIN).replace('# placeholder', END)}    listen 443 ssl;`)],
  ['duplicated complete blocks', s => s.replace('    listen 443 ssl;', `${GUARD}${GUARD}    listen 443 ssl;`)],
  ['extra end marker', s => s.replace('    listen 443 ssl;', `${GUARD}\n    ${END}\n    listen 443 ssl;`)],
  ['wrong www server', s => s.replace('server { listen 443 ssl;', `server {${GUARD} listen 443 ssl;`)],
  ['outside every server', s => GUARD + s],
  ['nested location', s => s.replace('    location / { try_files $uri $uri/ =404; }', `    location / {${GUARD} try_files $uri $uri/ =404; }`)],
  ['nested server if', s => s.replace('    listen 443 ssl;', `    if ($uri = /fixture) {${GUARD} return 200; }\n    listen 443 ssl;`)],
  ['tampered status', s => s.replace('    listen 443 ssl;', `${GUARD.replace('return 404;', 'return 403;')}    listen 443 ssl;`)],
  ['tampered URI variable', s => s.replace('    listen 443 ssl;', `${GUARD.replace('$uri', '$request_uri')}    listen 443 ssl;`)],
  ['tampered regex', s => s.replace('    listen 443 ssl;', `${GUARD.replace('^/+[.]git', '^/[.]git')}    listen 443 ssl;`)],
  ['unrelated directive', s => s.replace('    listen 443 ssl;', `${GUARD.replace('        return 404;', '        add_header X-Injection fixture;\n        return 404;')}    listen 443 ssl;`)],
  ['unrelated comment inside managed block', s => s.replace('    listen 443 ssl;', `${GUARD.replace('        return 404;', '        # changed managed content\n        return 404;')}    listen 443 ssl;`)],
  ['marker trailing text', s => s.replace('    listen 443 ssl;', `${GUARD.replace(END, `${END} changed`)}    listen 443 ssl;`)],
  ['guard CRLF tampering', s => s.replace('    listen 443 ssl;', `${GUARD.replaceAll('\n', '\r\n')}    listen 443 ssl;`)],
];
for (const [label, change] of invalidGuards) {
  test(`reject ${label} before any config/include write or reload, including --remove`, async t => {
    const fix = await fixture(t);
    const bytes = Buffer.from(change(fix.original));
    await fs.writeFile(fix.config, bytes);
    for (const extra of [[], ['--dry-run'], ['--remove']]) {
      const result = fix.run(extra);
      assert.notEqual(result.status, 0, `${label}: ${result.stdout}`);
      assert.deepEqual(await fs.readFile(fix.config), bytes);
      assert.equal(await fs.readFile(fix.include, 'utf8'), '# previous fixture include\n');
    }
    const logs = await fs.readFile(fix.log, 'utf8');
    assert.ok(!logs.includes('nginx -t') && !logs.includes('reload'));
  });
}

for (const failure of ['FAIL_TEST', 'FAIL_NEW_DUMP', 'OMIT_INCLUDE', 'FAIL_RELOAD']) {
  for (const existingInclude of [false, true]) {
    test(`${failure} restores exact originally unguarded config and ${existingInclude ? 'existing' : 'absent'} include`, async t => {
      const fix = await fixture(t);
      if (!existingInclude) await fs.unlink(fix.include);
      const before = await fs.readFile(fix.config);
      const result = fix.run([], { [failure]: '1' });
      assert.notEqual(result.status, 0);
      assert.match(result.stderr, /original disk config\/rules restored/);
      assert.deepEqual(await fs.readFile(fix.config), before);
      if (existingInclude) assert.equal(await fs.readFile(fix.include, 'utf8'), '# previous fixture include\n');
      else await assert.rejects(fs.access(fix.include), /ENOENT/);
      if (failure !== 'FAIL_RELOAD') assert.ok(!(await fs.readFile(fix.log, 'utf8')).includes('reload'));
    });
  }
}

