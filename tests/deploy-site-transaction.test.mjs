async function restored(fix, result) {
  assert.notEqual(result.status, 0, result.stdout);
  assert.match(result.stderr, /Frontend rollback complete/, result.stderr);
  for (const [relative, bytes] of Object.entries(fix.old)) {
    assert.equal(await fs.readFile(path.join(fix.site, relative), 'utf8'), bytes, relative);
  }
  for (const relative of ['new-checkout', 'new-generated', 'new-target', 'scripts/deploy-site-transaction.sh']) {
    await assert.rejects(fs.access(path.join(fix.site, relative)), /ENOENT/, relative);
  }
  assert.equal(await fs.readFile(path.join(fix.site, '.git/HEAD'), 'utf8'), 'old-sha\n');
  assert.equal(await fs.readFile(fix.include, 'utf8'), '# original rules\n');
  const backupName = (await fs.readdir(fix.root)).find(name => name.startsWith('sgeda-site-transaction-'));
  assert.ok(backupName, result.stderr);
  const backup = path.join(fix.root, backupName);
  assert.equal((await fs.stat(backup)).mode & 0o777, 0o700);
  assert.ok(!backup.startsWith(fix.site + '/'));
  assert.equal(await fs.readFile(path.join(backup, 'before/cms-published/live/index.html'), 'utf8'), fix.old['cms-published/live/index.html']);
  await assert.rejects(fs.access(path.join(backup, 'before/.env')), /ENOENT/);
  await assert.rejects(fs.access(path.join(backup, 'before/data/cms/pages.jsonl')), /ENOENT/);
  assert.ok(!result.stdout.includes('fixture-only'));
  assert.ok(!result.stderr.includes('fixture-only'));
  return backup;
}

