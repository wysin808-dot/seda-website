test('fixture mode rejects omitted/real/equivalent production paths and symlinks before commands or secret reads', async t => {
  const fix = await fixture(t);
  await put(fix.root, 'helper.sh', helper);
  const attempts = [
    ['--site-root', '/var/www/sgeda'],
    ['--site-root', '/var/www/../www/sgeda'],
    ['--config', '/etc/nginx/sites-available/sgeda'],
    ['--include-path', '/etc/nginx/snippets/school-redirects.nginx.conf'],
    ['--git-bin', '/usr/bin/git'],
  ];
  for (const extra of attempts) {
    const command = `set -euo pipefail; source ${quote(path.join(fix.root, 'helper.sh'))}; deploy_site_transaction_begin ${[...fix.args, ...extra].map(quote).join(' ')}`;
    const result = spawnSync('bash', ['-c', command], { env: fix.env, encoding: 'utf8' });
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /Test mode cannot access production or non-fixture paths/);
  }
  const omitted = fix.args.slice();
  omitted.splice(omitted.indexOf('--config'), 2);
  let result = spawnSync('bash', ['-c', `set -e; source ${quote(path.join(fix.root, 'helper.sh'))}; deploy_site_transaction_begin ${omitted.map(quote).join(' ')}`], { env: fix.env, encoding: 'utf8' });
  assert.notEqual(result.status, 0);
  await fs.symlink('/var/www/sgeda', path.join(fix.root, 'production-link'));
  result = spawnSync('bash', ['-c', `set -e; source ${quote(path.join(fix.root, 'helper.sh'))}; deploy_site_transaction_begin ${[...fix.args, '--site-root', path.join(fix.root, 'production-link')].map(quote).join(' ')}`], { env: fix.env, encoding: 'utf8' });
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /Symlink paths are not permitted/);
  await fs.symlink('/nonexistent-fixture-secret', path.join(fix.site, '.env.symlink'));
  result = spawnSync('bash', ['-c', `set -e; source ${quote(path.join(fix.root, 'helper.sh'))}; ${fix.begin}`], { env: fix.env, encoding: 'utf8' });
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /Fixture site cannot contain symlinks/);
  await assert.rejects(fs.access(fix.env.FIX_LOG), /ENOENT/);
  assert.ok(!(await fs.readdir(fix.root)).some(name => name.startsWith('sgeda-site-transaction-')));
});

