function mergeByKey(existing, incoming) {
  const map = new Map(existing.map((item) => [`${item.basePath}/${item.slug}`, item]));
  for (const item of incoming) {
    map.set(`${item.basePath}/${item.slug}`, item);
  }
  return [...map.values()];
}

