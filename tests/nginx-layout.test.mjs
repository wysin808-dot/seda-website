for (const kind of ['two-files', 'two-blocks', 'two-aliases', 'repeated-header', 'only-unrelated-loaded']) {
  test(`discovery refuses ${kind} before any transaction snapshot or frontend write`, async t => {
    const fix = await fixture(t);
    if (kind === 'two-files') {
      const other = await put(fix.root, 'nginx/conf.d/second.conf', fix.content);
      await fix.loaded([{ path: fix.config }, { path: other }]);
    } else if (kind === 'two-blocks') {
      await fs.writeFile(fix.config, fix.content + fix.content);
    } else if (kind === 'two-aliases') {
      const alias = path.join(fix.root, 'nginx/sites-enabled/also-loaded');
      await fs.mkdir(path.dirname(alias));
      await fs.symlink(fix.config, alias);
      await fix.loaded([{ path: fix.config }, { path: alias }]);
    } else if (kind === 'repeated-header') {
      await fix.loaded([{ path: fix.config }, { path: fix.config }]);
    } else {
      const other = await put(fix.root, 'nginx/conf.d/other.conf', fix.content.replaceAll('sgeda.org.cn', 'unrelated.example'));
      await fix.loaded([{ path: other }]);
    }
    const result = fix.runTransaction();
    assert.notEqual(result.status, 0);
    assert.equal(await fs.readFile(path.join(fix.site, 'index.html'), 'utf8'), 'OLD FRONTEND\n');
    assert.ok(!(await fs.readdir(fix.root)).some(x => x.startsWith('sgeda-site-transaction-')));
    assert.equal(await fs.readFile(fix.log, 'utf8'), 'nginx -T\n');
    cleanLogs(result);
  });
}

for (const [label, change] of [
  ['wrong root', s => s.replace(/root "[^"]+";/, 'root /wrong/root;')],
  ['missing server name', s => s.replace('server_name "sgeda.org.cn";', 'server_name unrelated.example;')],
  ['missing ssl', s => s.replace('443 ssl http2', '443 http2')],
  ['wrong port', s => s.replace('443 ssl http2', '444 ssl http2')],
  ['unix socket ending in 443', s => s.replace('[::]:443', 'unix:/fixture/socket:443')],
  ['nested root only', s => s.replace(/    root "[^"]+";\r\n/, '').replace('location /api/ {', 'location /api/ { root /wrong/root;')],
]) {
  test(`canonical selection rejects ${label}`, async t => {
    const fix = await fixture(t);
    const bytes = change(fix.content);
    await fs.writeFile(fix.config, bytes);
    const result = fix.runInstaller();
    assert.notEqual(result.status, 0);
    assert.equal(await fs.readFile(fix.config, 'utf8'), bytes);
    assert.match(result.stderr, /exactly one LOADED/);
    cleanLogs(result);
  });
}

