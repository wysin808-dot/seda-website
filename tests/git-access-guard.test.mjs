async function freePort() {
  const probe = createServer();
  probe.listen(0, '127.0.0.1');
  await once(probe, 'listening');
  const port = probe.address().port;
  await new Promise(resolve => probe.close(resolve));
  assert.ok(port > 1024);
  return port;
}

// Raw request path is deliberate: fetch/URL normalizes dot components client-side.
function request(port, rawPath, method = 'GET') {
  return new Promise((resolve, reject) => {
    const req = https.request({ hostname: '127.0.0.1', port, path: rawPath, method,
      headers: { Host: 'sgeda.org.cn' }, rejectUnauthorized: false, agent: false }, response => {
      let body = '';
      response.setEncoding('utf8');
      response.on('data', chunk => { body += chunk; });
      response.on('end', () => resolve({ status: response.statusCode, headers: response.headers, body }));
    });
    req.on('error', reject);
    req.setTimeout(2000, () => req.destroy(new Error('fixture request timeout')));
    req.end();
  });
}

async function withNginx(fix, canonical, mergeSlashes, callback) {
  const port = await freePort();
  assert.equal((await fs.stat(fix.root)).mode & 0o777, 0o700);
  // The installer was proven with canonical 443 by fake nginx. Only this fixture
  // listen is changed to a high loopback TLS port for real Nginx; not production.
  const privateServer = canonical.replace('listen 443 ssl;', `listen 127.0.0.1:${port} ssl;`);
  assert.equal(privateServer.replace(`listen 127.0.0.1:${port} ssl;`, 'listen 443 ssl;'), canonical);
  const fixtureUser = process.getuid?.() === 0 ? `user ${os.userInfo().username};\n` : '';
  const conf = await put(fix.root, 'private-runtime.conf', `${fixtureUser}pid ${fix.root}/nginx.pid;\nerror_log ${fix.root}/error.log;\nevents {}\nhttp { access_log off; merge_slashes ${mergeSlashes}; client_body_temp_path ${fix.root}/body; proxy_temp_path ${fix.root}/proxy; fastcgi_temp_path ${fix.root}/fastcgi; uwsgi_temp_path ${fix.root}/uwsgi; scgi_temp_path ${fix.root}/scgi;\n${privateServer}\n}\n`);
  const check = spawnSync('nginx', ['-p', `${fix.root}/`, '-c', conf, '-t'], { encoding: 'utf8' });
  assert.equal(check.status, 0, check.stderr);
  const nginx = spawn('nginx', ['-p', `${fix.root}/`, '-c', conf, '-g', 'daemon off;'], { stdio: ['ignore', 'ignore', 'pipe'] });
  const stopped = once(nginx, 'close');
  let errors = '';
  nginx.stderr.on('data', bytes => { errors += bytes; });
  try {
    let ready = false;
    for (let i = 0; i < 100; i++) {
      try { await request(port, '/'); ready = true; break; } catch { await pause(20); }
      if (nginx.exitCode !== null) break;
    }
    assert.ok(ready, errors);
    await callback(port);
  } finally {
    if (nginx.exitCode === null) nginx.kill('SIGTERM');
    await stopped;
  }
}

for (const mergeSlashes of ['on', 'off']) {
  test(`real private loopback TLS Nginx: unguarded fake Git is exposed, guard wins over exact/prefix/cache; merge_slashes ${mergeSlashes}`, { timeout: 30000 }, async t => {
    if (spawnSync('nginx', ['-v']).status !== 0 || spawnSync('openssl', ['version']).status !== 0) {
      t.skip('local nginx/openssl not installed'); return;
    }
    const fix = await fixture(t);
    const fakeGit = 'ENTIRELY FICTIONAL GIT FIXTURE; NOT A REAL REPOSITORY\n';
    for (const relative of ['.git/index.html', '.git/config', '.git/HEAD', '.git/objects/test.js', '.git/objects/test.css', '.git/objects/plain', '.git/objects/long/test.js']) await put(fix.site, relative, fakeGit);
    const normal = new Map([
      ['/', '<h1>ordinary fixture HTML</h1>\n'],
      ['/.well-known/acme-challenge/fake-token', 'fictional ACME token'],
      ['/.github/test', 'ordinary github fixture'],
      ['/.gitignore', 'ordinary gitignore fixture'],
    ]);
    for (const [route, body] of normal) if (route !== '/') await put(fix.site, route.slice(1), body);
    const certificate = spawnSync('openssl', ['req', '-x509', '-newkey', 'rsa:2048', '-nodes', '-days', '1', '-subj', '/CN=fixture.invalid', '-keyout', fix.key, '-out', fix.cert], { encoding: 'utf8' });
    assert.equal(certificate.status, 0, certificate.stderr);
    const installed = fix.run();
    assert.equal(installed.status, 0, installed.stderr);
    const text = await fs.readFile(fix.config, 'utf8');
    installedAtStart(text);
    const canonical = text.slice(text.indexOf('# CANONICAL'));
    await withNginx(fix, canonical.replace(GUARD, ''), mergeSlashes, async port => {
      for (const route of ['/.git/', '/.git/config', '/.git/HEAD', '/.git/objects/test.js', '/.git/objects/test.css', '/.git/objects/plain', '/.git/objects/long/test.js']) {
        const response = await request(port, route);
        assert.equal(response.status, 200, `unguarded ${route}`);
        assert.equal(response.body, fakeGit, route);
      }
      assert.equal((await request(port, '/.git/config')).headers['x-exact'], 'fixture');
      assert.equal((await request(port, '/.git/objects/plain')).headers['x-long-prefix'], 'fixture');
      assert.equal((await request(port, '/.git/objects/long/test.js')).headers['x-long-prefix'], 'fixture');
      assert.equal((await request(port, '/.git/objects/test.js')).headers['x-cache'], 'fixture');
      assert.ok((await request(port, '/.git/objects/test.css')).headers.expires);
    });
    const blocked = [
      '/.git', '/.git/', '/.git/config', '/.git/HEAD', '/.git/objects/test.js', '/.git/objects/test.css',
      '/.git/objects/plain', '/.git/objects/long/test.js', '/%2egit/config', '/%2Egit/HEAD',
      '/.git%2fconfig', '/%2egit%2Fobjects%2Ftest.js', '//.git', '///.git/config', '//%2egit/HEAD',
      '/./.git/config', '/ordinary/../.git/HEAD', '/ordinary/%2e%2e/%2egit/config',
      '/.git/objects/../config', '/.git/config?download=1', '/.git?file=HEAD',
    ];
    await withNginx(fix, canonical, mergeSlashes, async port => {
      for (const method of ['GET', 'HEAD']) {
        for (const route of blocked) {
          const response = await request(port, route, method);
          assert.equal(response.status, 404, `${mergeSlashes} ${method} ${route}`);
          assert.ok(!response.body.includes(fakeGit), route);
          assert.equal(response.headers.location, undefined, route);
          assert.equal(response.headers['x-exact'], undefined, route);
          assert.equal(response.headers['x-long-prefix'], undefined, route);
          assert.equal(response.headers['x-cache'], undefined, route);
          assert.equal(response.headers.expires, undefined, route);
          if (method === 'HEAD') assert.equal(response.body, '');
        }
        for (const [route, body] of normal) {
          const response = await request(port, route, method);
          assert.equal(response.status, 200, `${method} ${route}`);
          if (method === 'GET') assert.equal(response.body, body);
        }
        for (const [route, body] of [
          ['/api/config', 'fixture API config'],
          ['/api/config?path=/.git/config', 'fixture API config'],
          ['/api/.git/config', 'fixture nested API'],
          ['/?path=/.git/HEAD', normal.get('/')],
          ['/.git/../.github/test', normal.get('/.github/test')],
        ]) {
          const response = await request(port, route, method);
          assert.equal(response.status, 200, `${method} ${route}`);
          if (method === 'GET') assert.equal(response.body, body);
        }
        const redirect = await request(port, '/old-school/?source=fixture', method);
        assert.equal(redirect.status, 301);
        assert.equal(redirect.headers.location, 'https://sgeda.org.cn/new-target/#school-alpha');
      }
    });
  });
}
